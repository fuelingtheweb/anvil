<?php

namespace App\Commands\Build;

use App\Models\App;
use App\Models\Simlayer;
use LaravelZero\Framework\Commands\Command;
use Symfony\Component\Yaml\Yaml;

class Keys extends Command
{
    protected $signature = 'build:keys';

    protected $description = 'Build the Keys config (keys/keys.json)';

    public function handle()
    {
        $this->info('Building Keys Config...');

        $layers = collect(Yaml::parse(file_get_contents(anvil_config('simlayers'))))
            ->map(fn ($rules, $index) => (new Simlayer($index, $rules))->toKeys())
            ->filter()
            ->values();

        // The timings and the fn rule mirror src/templates/karabiner.edn.
        $config = [
            'comment' => 'Generated by `php artisan build:keys` from config/simlayers.yml: edit that, not this.',
            'version' => 1,
            'simlayerThresholdMs' => 250,
            'hyperAloneTimeoutMs' => 1000,
            'hyperAlone' => [['key' => 'escape']],
            'apps' => (object) App::bundles()->all(),
            'layers' => $layers->all(),
            'rules' => [
                ['from' => 'fn', 'actions' => [['pointer' => 'button1']]], // Mouse click. Hold for dragging
            ],
        ];

        if (! is_dir(base_path('keys'))) {
            mkdir(base_path('keys'));
        }

        file_put_contents(
            base_path('keys/keys.json'),
            json_encode($config, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) . "\n",
        );

        $this->info('Finished!');
    }
}
